int	get_letter(char c, int row)
{
	char	upper;

	if (ft_isalpha((unsigned char)c))
	{
		upper = ft_toupper((unsigned char)c);
		if (upper >= 'A' && upper <= 'J')
			return (get_letter_a_to_j(upper, row));
		if (upper >= 'K' && upper <= 'T')
			return (get_letter_k_to_t(upper, row));
		return (get_letter_u_to_z(upper, row));
	}
	return (0);
}
