int	get_letter(char c, int row)
{
	char	upper;

	if (ft_isalpha((unsigned char)c))
	{
		upper = ft_toupper((unsigned char)c);
		if (upper >= 'A' && upper <= 'M')
			return (get_letter_a_to_m(upper, row));
		return (get_letter_n_to_z(upper, row));
	}
	return (0);
}

