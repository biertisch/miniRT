int	get_symbol(char c, int row)
{
	static const int	symbols[5][12] = {
	{0x0030, 0x0070, 0x00E0, 0x01C0, 0x0180, 0x0180,
		0x0180, 0x01C0, 0x00E0, 0x0070, 0x0030, 0x0000},
	{0x0C00, 0x0E00, 0x0700, 0x0380, 0x0180, 0x0180,
		0x0180, 0x0380, 0x0700, 0x0E00, 0x0C00, 0x0000},
	{0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000,
		0x0C00, 0x0C00, 0x1800, 0x1800, 0x3000, 0x0000},
	{0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000,
		0x0C00, 0x0C00, 0x0C00, 0x0000, 0x0000, 0x0000},
	{0x0000, 0x0000, 0x0000, 0x0000, 0x0FFC, 0x0FFC,
		0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000}
	};

	if (c == '(')
		return (symbols[0][row]);
	if (c == ')')
		return (symbols[1][row]);
	if (c == ',')
		return (symbols[2][row]);
	if (c == '.')
		return (symbols[3][row]);
	if (c == '-')
		return (symbols[4][row]);
	return (0);
}

